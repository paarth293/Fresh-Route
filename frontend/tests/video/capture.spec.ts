import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

test('capture the real submission walkthrough', async ({ page, request }) => {
  const root = path.resolve('../work/video');
  fs.mkdirSync(path.join(root, 'screens'), { recursive: true });
  const start = Date.now();
  const marks: Record<string, number> = {};
  const mark = (name: string) => { marks[name] = (Date.now() - start) / 1000; };
  const shot = async (name: string, selector?: string) => {
    await page.mouse.move(0, 0);
    if (selector) await page.locator(selector).first().screenshot({ path: path.join(root, 'screens', `${name}.png`) });
    else { await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: path.join(root, 'screens', `${name}.png`) }); }
  };
  const samples = await (await request.get('/api/v1/demo-scenarios')).json();
  await request.post('/api/v1/scenarios', { data: samples.find((s: any) => s.scenario_id === 'demo-normal-001') });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Generate plan', exact: true })).toBeEnabled();
  mark('overview_start'); await shot('overview_empty');
  await page.getByRole('button', { name: 'Generate plan', exact: true }).click();
  await expect(page.getByText('Plan generated and independently validated.')).toBeVisible({ timeout: 30_000 });
  mark('overview_solved'); await shot('overview'); await shot('network', '.network-panel');
  await shot('metrics', '.cards');
  await page.getByRole('button', { name: 'Inventory', exact: true }).click();
  mark('inventory_start'); await shot('inventory'); await shot('inventory_table', '.work-panel');
  await page.getByRole('button', { name: 'View receipt' }).first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  mark('receipt'); await shot('receipt', '.modal');
  await page.getByRole('button', { name: 'Close receipt' }).click();
  await page.getByRole('button', { name: 'Dispatch', exact: true }).click();
  mark('dispatch'); await shot('dispatch'); await shot('trips', '.table-wrap');
  await shot('deadlines', '.table-wrap:nth-of-type(3)');
  await page.getByRole('button', { name: 'Evaluation', exact: true }).click();
  await page.getByRole('button', { name: 'Run replay', exact: true }).click();
  await expect(page.getByText(/Inventory reconciled: Yes/)).toBeVisible({ timeout: 30_000 });
  mark('replay'); await shot('replay');
  await page.getByRole('button', { name: 'Commit plan', exact: true }).click();
  await expect(page.getByText('Trips reserved. Generate a new plan for remaining stock.')).toBeVisible();
  await page.getByRole('button', { name: 'Disruptions', exact: true }).click();
  mark('commitments'); await shot('commitments');
  await page.getByLabel('Delay minutes').fill('20');
  await page.getByRole('button', { name: 'Apply delay', exact: true }).click();
  await expect(page.getByText(/Delay recorded/)).toBeVisible();
  await page.getByRole('button', { name: 'Generate plan', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('operator intervention is required');
  mark('delay_conflict'); await shot('delay_conflict');
  await page.getByRole('button', { name: 'Release reservation V-TRUCK-01 R-EAST', exact: true }).click();
  await expect(page.getByText(/Reservation released and cancellation fee recorded/)).toBeVisible();
  await page.getByRole('button', { name: 'Generate plan', exact: true }).click();
  await expect(page.getByText('Plan generated and independently validated.')).toBeVisible({ timeout: 30_000 });
  mark('recovery'); await shot('recovery');
  // Start a fresh version for the inspection demonstration, preserving earlier plans.
  await request.post('/api/v1/scenarios', { data: samples.find((s: any) => s.scenario_id === 'demo-normal-001') });
  await page.reload();
  await expect(page.getByRole('button', { name: 'Generate plan', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Inspections', exact: true }).click();
  mark('inspection_start');
  await page.getByRole('button', { name: 'Rank inspections', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Simulate inspection' }).first()).toBeEnabled({ timeout: 120_000 });
  mark('inspection_ranked'); await shot('inspections'); await shot('inspection_table', '.work-panel');
  await page.getByRole('button', { name: 'Simulate inspection' }).first().click();
  await expect(page.getByText(/Observed .* life for/)).toBeVisible({ timeout: 30_000 });
  mark('inspection_observed'); await shot('inspection_observed');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await shot('mobile');
  mark('end');
  fs.writeFileSync(path.join(root, 'capture.json'), JSON.stringify({ marks, video: await page.video()?.path() }, null, 2));
});
