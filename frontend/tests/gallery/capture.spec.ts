import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

test('capture gallery from the real application', async ({ page, request }) => {
  const out = path.resolve('../deliverables/project-gallery');
  fs.mkdirSync(out, { recursive: true });
  const shot = async (file: string) => {
    await page.mouse.move(0, 0);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.waitForTimeout(350);
    await page.screenshot({ path: path.join(out, file), animations: 'disabled' });
  };
  const samples = await (await request.get('/api/v1/demo-scenarios')).json();
  const normal = samples.find((s: any) => s.scenario_id === 'demo-normal-001');
  expect((await request.post('/api/v1/scenarios', { data: normal })).status()).toBe(201);
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Generate plan', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Generate plan', exact: true }).click();
  await expect(page.getByText('Plan generated and independently validated.')).toBeVisible({ timeout: 60_000 });
  await shot('02-working-overview.png');
  await page.getByRole('button', { name: 'Inventory', exact: true }).click();
  await page.getByRole('button', { name: 'View receipt' }).first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await shot('03-explainable-decision-receipt.png');
  await page.getByRole('button', { name: 'Close receipt' }).click();
  await page.getByRole('button', { name: 'Dispatch', exact: true }).click();
  await shot('04-dispatch-and-allocations.png');
  await page.getByRole('button', { name: 'Evaluation', exact: true }).click();
  await page.getByRole('button', { name: 'Run replay', exact: true }).click();
  await expect(page.getByText(/Inventory reconciled: Yes/)).toBeVisible({ timeout: 60_000 });
  await shot('07-simulated-outcomes.png');
  await page.getByRole('button', { name: 'Commit plan', exact: true }).click();
  await expect(page.getByText('Trips reserved. Generate a new plan for remaining stock.')).toBeVisible();
  await page.getByRole('button', { name: 'Disruptions', exact: true }).click();
  await page.getByLabel('Route', { exact: true }).selectOption('R-EAST');
  await page.getByLabel('Delay minutes').fill('20');
  await page.getByRole('button', { name: 'Apply delay', exact: true }).click();
  await expect(page.getByText(/Delay recorded/)).toBeVisible();
  await shot('05-commitments-and-recovery.png');
  expect((await request.post('/api/v1/scenarios', { data: normal })).status()).toBe(201);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Generate plan', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Inspections', exact: true }).click();
  await page.getByRole('button', { name: 'Rank inspections', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Simulate inspection' }).first()).toBeEnabled({ timeout: 150_000 });
  await shot('06-inspection-value-ranking.png');
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.getByRole('button', { name: 'Generate plan', exact: true }).click();
  await expect(page.getByText('Plan generated and independently validated.')).toBeVisible({ timeout: 60_000 });
  await page.setViewportSize({ width: 390, height: 844 });
  await shot('08-mobile-workspace.png');
});
